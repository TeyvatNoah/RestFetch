using System.Runtime.CompilerServices;

using Cysharp.Text;

using Microsoft.CodeAnalysis;

namespace RestFetch.SourceGenerator;

public sealed class SourceBuilder: IDisposable {
	public Utf16ValueStringBuilder StringBuilder = ZString.CreateStringBuilder();
	private int _indentLevel = 0;

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public SourceBuilder Append<T>(T arg, bool lineStart = false) {
		if (_indentLevel > 0 && lineStart) {
			StringBuilder.Append('\t', _indentLevel);
		}
		StringBuilder.Append(arg);
		return this;
	}

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public SourceBuilder AppendLine<T>(T arg) {
		if (_indentLevel > 0) {
			StringBuilder.Append('\t', _indentLevel);
		}
		StringBuilder.AppendLine(arg);
		return this;
	}

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public SourceBuilder CreateFile(Action<SourceBuilder>? fillContent) {
		StringBuilder.Append("""
// <auto-generated />
#nullable enable


""");
		fillContent?.Invoke(this);
		return this;
	}

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public SourceBuilder CreateNamespace(NamespaceInfo? ns) {
		if (ns is null || ns.IsGlobalNamespace) {
			return this;
		}
		Append("namespace ", true)
		.Append(ns.FullyQualifiedName)
		.Append(";\n\n");
		return this;
	}

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public SourceBuilder CreateUsing(NamespaceInfo? ns, bool global = false) {
		if (ns is null) {
			return this;
		}
		if (global) {
			Append("global ", true);
		}
		Append("using ", !global)
		.Append(ns.FullyQualifiedName)
		.Append(";\n");
		return this;
	}

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public SourceBuilder CreateUsing(string? ns, bool global = false) {
		if (ns is null) {
			return this;
		}
		if (global) {
			Append("global ", true);
		}
		Append("using ", !global)
		.Append(ns)
		.Append(";\n");
		return this;
	}

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public SourceBuilder CreateIndent(Action<SourceBuilder>? fillContent) {
		StringBuilder.AppendLine();
		++_indentLevel;
		fillContent?.Invoke(this);
		--_indentLevel;
		StringBuilder.AppendLine();
		return this;
	}

	// typeName给interface生成对应类型时指定类型名
	public SourceBuilder CreateType(string ns, Version version, TypeInfo type, Action<SourceBuilder>? fillContent, bool withContainingType, string? typeName = null, string? iface = null) {
		static void AppendTypeHeader(SourceBuilder sb, string ns, Version version, TypeInfo type, string? typeName, string? @interface) {

			var accessibility = type.DeclaredAccessibility switch {
				Accessibility.Public => "public ",
				Accessibility.Internal => "internal ",
				Accessibility.Private => "private ",
				Accessibility.Protected => "protected ",
				Accessibility.ProtectedAndInternal => "private protected ",
				Accessibility.ProtectedOrInternal => "protected internal ",
				_ => ""
			};
			sb.AppendLine("#pragma warning disable CS0693");

			sb.Append(accessibility, true);

			if (type.IsStatic) {
				sb.Append("static ");
			}
			if (!type.IsStatic && type.IsAbstract && type.TypeKind == TypeKind.Class) {
				sb.Append("abstract ");
			}
			if (!type.IsStatic && type.IsSealed && (type.TypeKind == TypeKind.Class || typeName is not null) && !type.IsValueType) {
				sb.Append("sealed ");
			}

			if (type.IsReadOnly) {
				sb.Append("readonly ");
			}

			if (type.IsRefLikeType) {
				sb.Append("ref ");
			}

			if (typeName is null && type.IsPartial) {
				sb.Append("partial ");
			}

			var typekind = type.IsRecord ?
				type.IsValueType ? "record struct " : "record "
				: type.TypeKind switch {
					TypeKind.Class => "class ",
					TypeKind.Struct => "struct ",
					TypeKind.Interface => "interface ",
					_ => "class "
				};
			if (!string.IsNullOrEmpty(typeName)) {
				sb.Append("class ");
			} else {
				sb.Append(typekind);
			}

			// 接口
			if (!string.IsNullOrEmpty(typeName)) {
				sb.Append(typeName);
				if (type.IsGenericType && !type.TypeParameters.IsEmpty) {
					sb.Append('<');
					sb.StringBuilder.AppendJoin(',', type.TypeParameters.Select(static t => t.Name));
					sb.Append('>');
				}
				sb.Append(": ");
				if (@interface is not null) {
					sb.Append(@interface).Append(", ");
				}
				sb.Append(type.FullyQualifiedNameWithGlobalAndWhereClauses);
				// if (!string.IsNullOrEmpty(type.WhereClauses)) {
				// 	sb.Append('\n').Append(type.WhereClauses);
				// }
			} else if (type.IsGenericType) {
				sb.Append(type.MinimallyQualifiedName);
				if (@interface is not null) {
					sb.Append(": ")
					.Append(@interface);
				}
			} else {
				sb.Append(type.Name);
				if (@interface is not null) {
					sb.Append(": ")
					.Append(@interface);
				}
			}

			sb.Append(" {\n");
			sb.AppendLine("#pragma warning restore CS0693\n");
		}


		SourceBuilder CreateTypeInternal(string ns, Version version, string innerTypeName, TypeInfo type, Action<SourceBuilder>? fillContent, string? typeName = null, string? iface = null) {
			if (type.ContainingType is null) {
				AppendTypeHeader(this, ns, version, type, typeName, iface);
				fillContent?.Invoke(this);
				AppendLine("}\n");
				return this;
			} else {
				return CreateTypeInternal(ns, version, innerTypeName, type.ContainingType,
					sb => sb.CreateIndent(sb => {
						if (type.MinimallyQualifiedName == innerTypeName) {
							AppendLine("[global::System.Runtime.CompilerServices.CompilerGeneratedAttribute]")
							.Append($@"[global::System.CodeDom.Compiler.GeneratedCodeAttribute(""", true)
							.Append(ns)
							.Append(@""", """)
							.Append(version.ToString())
							.Append(@""")]")
							.Append('\n');
						}
						AppendTypeHeader(sb, ns, version, type, typeName, iface);
						fillContent?.Invoke(sb);
						sb.AppendLine("}\n");
				}), null, null);
			}
		}

		if (withContainingType) {
			return CreateTypeInternal(ns, version, type.MinimallyQualifiedName, type, fillContent, typeName, iface);
		} else {
			AppendLine("[global::System.Runtime.CompilerServices.CompilerGeneratedAttribute]")
			.Append($@"[global::System.CodeDom.Compiler.GeneratedCodeAttribute(""", true)
			.Append(ns)
			.Append(@""", """)
			.Append(version.ToString())
			.Append(@""")]")
			.Append('\n');
			AppendTypeHeader(this, ns, version, type, typeName, iface);
			fillContent?.Invoke(this);
			AppendLine("}\n");
			return this;
		}

	}


