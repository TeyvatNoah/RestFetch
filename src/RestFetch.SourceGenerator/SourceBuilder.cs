	public SourceBuilder CreateMethod(string ns, Version version, MethodInfo methodInfo, Action<SourceBuilder>? fillContent) {
			AppendLine("[global::System.Runtime.CompilerServices.CompilerGeneratedAttribute]")
			.Append($@"[global::System.CodeDom.Compiler.GeneratedCodeAttribute(""", true)
			.Append(ns)
			.Append(@""", """)
			.Append(version.ToString())
			.Append(@""")]")
			.Append('\n');

			var accessibility = methodInfo.DeclaredAccessibility switch {
				Accessibility.Public => "public ",
				Accessibility.Internal => "internal ",
				Accessibility.Private => "private ",
				Accessibility.Protected => "protected ",
				Accessibility.ProtectedAndInternal => "private protected ",
				Accessibility.ProtectedOrInternal => "protected internal ",
				_ => ""
			};
			Append(accessibility, true);

			if (methodInfo.IsStatic) {
				Append("static ");
			} else {
				if (methodInfo.IsReadOnly) {
					Append("readonly ");
				}
				if (methodInfo.IsSealed && methodInfo.IsOverride) {
					Append("sealed ");
				}
				if (methodInfo.IsOverride) {
					Append("override ");
				}
				if (methodInfo.IsVirtual) {
					Append("virtual ");
				}
			}

			if (methodInfo.IsAsync || methodInfo.IsAsyncReturnType) {
				Append("async ");
			}

			if (methodInfo.IsPartialDefinition) {
				Append("partial ");
			}
			if (methodInfo.ReturnsByRef) {
				Append("ref ");
			} else if (methodInfo.ReturnsByRefReadonly) {
				Append("ref readonly ");
			}

			if (methodInfo.ReturnsVoid || methodInfo.ReturnType.IsVoid) {
				Append("void ");
			} else {
				Append(methodInfo.ReturnTypeFullyQualifiedName).Append(' ');
			}

			Append(methodInfo.Name);

			if (methodInfo.IsGenericMethod && !methodInfo.TypeParameters.IsEmpty) {
				Append('<');
				StringBuilder.AppendJoin(',', methodInfo.TypeParameters.Select(static type => type.FullyQualifiedNameWithGlobal).ToArray());
				Append('>');
			}
			Append('(');
			StringBuilder.AppendJoin(", ", methodInfo.Parameters.Select(param => {
				using var innerSb = ZString.CreateStringBuilder();
				if (param.ScopedKind == ScopedKind.ScopedRef || param.ScopedKind == ScopedKind.ScopedValue) {
					innerSb.Append("scoped ");
				}

				if (param.IsParams || param.IsParamsArray) {
					innerSb.Append("params ");
				}

				if (param.RefKind == RefKind.Ref) {
					innerSb.Append("ref ");
				} else if (param.RefKind == RefKind.In) {
					innerSb.Append("in ");
				} else if (param.RefKind == RefKind.Out) {
					innerSb.Append("out ");
				} else if (param.RefKind == RefKind.RefReadOnlyParameter) {
					innerSb.Append("ref readonly ");
				}
				innerSb.Append(param.Type.FullyQualifiedNameWithGlobal);
				// if (param.Type.IsNullable) {
				// 	innerSb.Append('?');
				// }
				innerSb.Append(' ');
				innerSb.Append(param.Name);
				if (param.HasExplicitDefaultValue) {
					innerSb.Append(" = ");
					innerSb.Append(param.ExplicitDefaultValue);
				}
				return innerSb.ToString();
			}).ToArray());
			Append(") ");

			if (methodInfo.IsGenericMethod) {
				Append(methodInfo.WhereClauses);
			}
			// if (!string.IsNullOrEmpty(type.WhereClauses)) {
			// 	sb.Append('\n').Append(type.WhereClauses);
			// }

			Append('{');
			fillContent?.Invoke(this);
			AppendLine("}\n");
			return this;
	}

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public override string ToString() => StringBuilder.ToString();

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public void Dispose() => StringBuilder.Dispose();
}
